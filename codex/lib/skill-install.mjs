// Guide installation only: no desktop action, helper launch, service restart or credential access.
import { cp, mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { configurationState } from './plugin-state.mjs';
export { pluginState } from './plugin-state.mjs';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const LINK = '// NexusWindows entry link; generated from the installed package.\n';
const read = file => readFile(file, 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
export const codexHome = () => process.env.CODEX_HOME || path.join(os.homedir(), '.codex');

function guideRoot(root) {
  const dir = ['skills', 'skill'].map(name => path.join(root, name, 'nexus-windows'))
    .find(candidate => existsSync(path.join(candidate, 'SKILL.md')) && existsSync(path.join(candidate, 'entry.mjs')));
  if (!dir) throw new Error('The NexusWindows package is missing its skill or portable entry.');
  return dir;
}

async function atomicText(file, text) {
  if (await read(file) === text) return false;
  await mkdir(path.dirname(file), { recursive: true });
  const temporary = `${file}.${randomUUID()}.tmp`;
  await writeFile(temporary, text, 'utf8');
  await rename(temporary, file);
  return true;
}

export async function installSkill({ root = ROOT, home = codexHome() } = {}) {
  const { plugin: state, mcp } = configurationState(await read(path.join(home, 'config.toml')) ?? '');
  const target = path.join(home, 'skills', 'nexus-windows');
  if (state !== 'absent' || mcp === 'disabled') {
    // Only migrate a standalone guide written by this product, never an unrelated or edited personal skill.
    const previous = await read(path.join(target, 'entry.mjs'));
    const previousGuide = await read(path.join(target, 'SKILL.md'));
    if (/^name:\s*nexus-windows\s*$/m.test(previousGuide ?? '') && previous !== null &&
        (previous.startsWith(LINK) || /^\/\/ Generated by (?:NexusWindows\/codex\/)?install\.ps1\./.test(previous))) {
      const backup = path.join(home, 'backups', `skill-nexus-windows-${randomUUID()}`);
      await mkdir(path.dirname(backup), { recursive: true });
      await rename(target, backup);
    }
    return state === 'disabled' || mcp === 'disabled' ? 'disabled' : 'plugin';
  }
  const source = guideRoot(root);
  await mkdir(target, { recursive: true });
  await cp(source, target, { recursive: true });
  await atomicText(path.join(target, 'entry.mjs'), `${LINK}export * from ${JSON.stringify(pathToFileURL(path.join(source, 'entry.mjs')).href)};\n`);
  return 'installed';
}
